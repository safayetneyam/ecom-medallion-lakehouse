#!/usr/bin/env python3
"""Render data_out/dirty_data_report.json into generator/dirty_data_report.md (committable)."""
import argparse
import json
import os

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="./data_out")
ap.add_argument("--md", default=os.path.join(os.path.dirname(__file__), "dirty_data_report.md"))
a = ap.parse_args()
r = json.load(open(os.path.join(a.dir, "dirty_data_report.json")))
ref = r["reference_values"]

L = []
L.append("# Dirty-data report: synthetic e-commerce sources\n")
L.append(f"Generated by `generate_data.py` with **seed {r['seed']}**. Dataset \"as-of\" date: "
         f"**{r['dataset_as_of'][:10]}** (anything later is a *future* timestamp). Clean order dates span "
         f"{r['clean_order_date_range'][0]} to {r['clean_order_date_range'][1]}. All data is synthetic.\n")
L.append("## Source files\n")
L.append("| File | Data rows (excl. header) | Bytes | SHA-256 |")
L.append("|---|---:|---:|---|")
for f, s in r["files"].items():
    L.append(f"| `{f}` | {s['data_rows']:,} | {s['bytes']:,} | `{s['sha256']}` |")
L.append("\nRe-running the generator with the same seed reproduces these files byte-for-byte "
         "(same SHA-256). Volume path after upload: `/Volumes/<catalog>/ecom_poc/raw_files/`.\n")

for ds, title in (("orders", "orders.csv"), ("transactions", "transactions.csv")):
    d = r[ds]
    total = d["untouched_rows"] + d["anomaly_rows"]
    L.append(f"## {title}: injected anomalies\n")
    L.append("Each row carries **at most one** injected anomaly, so the counts are exact and disjoint.\n")
    L.append("| # | Anomaly | Field | Rows | % of file | Expected Silver outcome |")
    L.append("|---:|---|---|---:|---:|---|")
    for i, x in enumerate(d["inventory"], 1):
        L.append(f"| {i} | `{x['anomaly']}` | {x['field']} | {x['rows']:,} | {x['pct']:.2f}% | "
                 f"{x['expected_silver_outcome']} |")
    L.append(f"| | **Total anomalous rows** | | **{d['anomaly_rows']:,}** | "
             f"**{100 * d['anomaly_rows'] / total:.2f}%** | |")
    L.append(f"| | Untouched rows | | {d['untouched_rows']:,} | {100 * d['untouched_rows'] / total:.2f}% | |\n")

L.append("### What these numbers mean for Silver\n")
L.append("* **Quarantine candidates:** rows with a hard rule failure (null mandatory field, unparseable or "
         "out-of-range number, invalid/future timestamp, unknown status/currency, orphan/null order reference).")
L.append("* **Standardise & accept:** `inconsistent_case_whitespace` rows are valid once you `trim()` + "
         "normalise case; they should *not* be quarantined. That's a test that your rules clean before "
         "they reject.")
L.append("* **Duplicate losers:** `exact_duplicate_row` (whole row repeated) and `duplicate_*_id_diff_content` "
         "(same business key, different status/quantity/timestamp, like a re-extracted update). Each injected "
         "duplicate pairs with one clean original, so expect exactly one loser per injected row.")
L.append("* **Derived orphans (not injected):** some otherwise-valid transactions point at an order whose row "
         "is quarantined in Silver. Whether those count as orphans depends on whether you check the relationship "
         "against Bronze or against accepted `silver_orders`. Document your choice.\n")

L.append("## Realistic (non-dirty) business patterns\n")
L.append("Transactions per order, by pattern (clean base before anomaly injection):\n")
L.append("| Pattern | Orders | Meaning |")
L.append("|---|---:|---|")
meaning = {
    "none": "no payment row (pending or cancelled before payment)",
    "single": "one SUCCESS payment",
    "single_failed": "one FAILED payment (cancelled order)",
    "single_pending": "one PENDING payment",
    "retry": "FAILED attempt, then SUCCESS a few minutes later",
    "split": "two SUCCESS payments, each half the order total (partial payments)",
    "refund": "SUCCESS, then a REFUNDED row 2 to 20 days later (returned or cancelled)",
}
for k, v in r["transaction_patterns_per_order"].items():
    L.append(f"| `{k}` | {v:,} | {meaning[k]} |")
L.append("\nThese patterns are there so your **revenue definition** has to decide how to handle failed retries, "
         "split payments and refunds, and so joins between orders and transactions can fan out if you're careless.\n")

L.append("## Reference values for Silver rules\n")
L.append(f"* Order statuses: {', '.join(f'`{x}`' for x in ref['allowed_order_statuses'])}")
L.append(f"* Categories: {', '.join(f'`{x}`' for x in ref['allowed_categories'])}")
L.append(f"* Countries: {', '.join(f'`{x}`' for x in ref['allowed_countries'])}")
L.append(f"* Payment methods: {', '.join(f'`{x}`' for x in ref['allowed_payment_methods'])}")
L.append(f"* Transaction statuses: {', '.join(f'`{x}`' for x in ref['allowed_txn_statuses'])}")
L.append(f"* Supported currencies: {', '.join(f'`{x}`' for x in ref['supported_currencies'])} "
         "(see `fx_rates.csv`; static rates, USD per unit)")
L.append(f"* `quantity` between {ref['quantity_range'][0]} and {ref['quantity_range'][1]}; `unit_price` "
         f"between {ref['unit_price_range_usd'][0]} and {ref['unit_price_range_usd'][1]:,} (USD); "
         f"transaction amount converted to USD must not exceed {ref['max_txn_amount']:,.0f}")
L.append("* Null-like tokens to treat as NULL after `trim()`: `''`, `NULL`, `null`, `None`, `N/A`, `n/a`")
L.append("* Date format `yyyy-MM-dd` (order_date); timestamp format `yyyy-MM-dd HH:mm:ss` (txn_ts)\n")

L.append("## Why the anomalies stay a small, measured fraction\n")
po = 100 * r["orders"]["anomaly_rows"] / 1e6 if r["files"]["orders.csv"]["data_rows"] == 1_000_000 else 0
pt = 100 * r["transactions"]["anomaly_rows"] / 1e6 if r["files"]["transactions.csv"]["data_rows"] == 1_000_000 else 0
L.append(f"About {po:.1f}% of order rows and {pt:.1f}% of transaction rows are anomalous. Of that, 3 points are "
         "cosmetic case and whitespace issues that Silver should fix rather than reject, and every other class sits "
         "between 0.2% and 1%. That keeps the dataset representative, so the Gold metrics still describe a believable "
         "business, while giving each rule enough hits to be visible in the reconciliation. Because every "
         "count is known in advance, each Silver rule can be checked exactly (expected rows equal quarantined "
         "rows). If the dirty share were large or unknown, you couldn't tell a broken rule from bad data.\n")

L.append("## How to reproduce\n")
L.append("```bash\npython generator/generate_data.py --out ./data_out      # ~15 s, ~150 MB\n"
         "python generator/verify_data.py   --dir ./data_out      # independent re-detection of every count\n"
         "python generator/make_report_md.py --dir ./data_out     # refresh this report\n```")

open(a.md, "w").write("\n".join(L) + "\n")
print("wrote", a.md)
